export function DropdownMenuSubTrigger({
  className,
  inset,
  children,
  ...props
}: ComponentProps<typeof DropdownMenuPrimitive.SubTrigger> & { inset?: boolean }) {
  return (
    <DropdownMenuPrimitive.SubTrigger
      data-slot="dropdown-menu-sub-trigger"
      data-inset={inset}
      className={cn(
        'flex cursor-default items-center rounded-lg px-2 py-2 text-sm outline-hidden select-none',
        'focus:bg-secondary focus:text-secondary-foreground',
        'data-[state=open]:bg-secondary data-[state=open]:text-secondary-foreground',
        'data-[inset]:pl-8',
        className,
      )}
      {...props}
    >
      {children}
      <ChevronRightIcon className="ml-auto size-4" />
    </DropdownMenuPrimitive.SubTrigger>
  )
}

export function DropdownMenuSubContent({
  className,
  ...props
}: ComponentProps<typeof DropdownMenuPrimitive.SubContent>) {
  return (
    <DropdownMenuPrimitive.SubContent
      data-slot="dropdown-menu-sub-content"
      className={cn(
        'bg-popover text-popover-foreground border-border shadow-lifted z-50',
        'min-w-[8rem] overflow-hidden rounded-xl border p-1.5',
        'origin-(--radix-dropdown-menu-content-transform-origin)',
        contentMotion,
        className,
      )}
      {...props}
    />
  )
}
